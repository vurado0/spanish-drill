#!/usr/bin/env python3
"""
Builds data/en_verbs.js (English verbs for Spanish speakers) from scripts/source/en_verbs.txt.
No dependencies:  python3 scripts/build_en.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "source" / "en_verbs.txt"
OUT = ROOT / "data" / "en_verbs.js"
VOWELS = "aeiou"


def s3(b):
    if b == "have":
        return "has"
    if b == "be":
        return "is"
    if b.endswith(("s", "x", "z", "ch", "sh", "o")):
        return b + "es"
    if b.endswith("y") and b[-2] not in VOWELS:
        return b[:-1] + "ies"
    return b + "s"


def past_regular(b):
    if b.endswith("e"):
        return b + "d"
    if b.endswith("y") and b[-2] not in VOWELS:
        return b[:-1] + "ied"
    return b + "ed"


def ing(b, past):
    if b.endswith("ie"):
        return b[:-2] + "ying"
    # doubled consonant in an explicit regular past (stopped -> stopping)
    if past.endswith("ed") and len(past) >= len(b) + 3 and past[len(b)] == b[-1] and past[: len(b)] == b:
        return b + b[-1] + "ing"
    if b.endswith("e") and not b.endswith(("ee", "oe", "ye")) and b != "be":
        return b[:-1] + "ing"
    return b + "ing"


def main():
    out = []
    for line in SRC.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = (line.split("|") + ["", "", "", ""])[:5]
        base, es, past, pp, ing_f = [p.strip() for p in parts]
        reg_past = past_regular(base)
        past_l = past.split("/") if past else [reg_past]
        pp_l = pp.split("/") if pp else list(past_l)
        def is_reg(f):
            return f == reg_past or (f.endswith("ed") and f.startswith(base))
        irregular = not is_reg(past_l[0]) or not is_reg(pp_l[0])
        tags = []
        if irregular:
            p0, pp0 = past_l[0], pp_l[0]
            if base == "be":
                grp = "A-B-C"
            elif base == p0 == pp0:
                grp = "A-A-A"
            elif p0 == pp0:
                grp = "A-B-B"
            elif pp0 == base:
                grp = "A-B-A"
            else:
                grp = "A-B-C"
            tags = ["irregular", grp]
            if (len(past_l) > 1 or len(pp_l) > 1) and base != "be":
                tags.append("UK / US")
        else:
            tags = ["regular"]
            if past_l[0] != reg_past:
                tags.append("double consonant")
            elif base.endswith("y") and base[-2] not in VOWELS:
                tags.append("y → ied")
            if len(past_l) > 1:
                tags.append("UK / US")
        ing_l = ing_f.split("/") if ing_f else [ing(base, past_l[0])]
        out.append({"b": base, "es": es, "s3": s3(base), "past": past_l, "pp": pp_l, "ing": ing_l,
                    "irr": int(irregular), "tags": tags})
    out = out[:200]
    OUT.write_text("// Generated by scripts/build_en.py — 200 English verbs (English → Spanish).\n"
                   "window.EN_VERB_DATA = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print("english verbs:", len(out), "| irregular:", sum(v["irr"] for v in out))


if __name__ == "__main__":
    main()
